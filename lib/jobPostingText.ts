/** Lee una clave con prefijo (`status_DRAFT`). Si no existe, devuelve el código tal cual. */
export function pick(tx: JobText, prefix: string, key: string): string {
  return (tx as Record<string, string>)[`${prefix}_${key}`] ?? key;
}

/** Mensaje por clave dinámica (los `v_*` de validación y los `err_*`). */
export function msg(tx: JobText, key: string): string {
  return (tx as Record<string, string>)[key] ?? key;
}
