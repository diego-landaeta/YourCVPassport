export function getPublishedPosts(lang: string): Omit<BlogPostData, 'content'>[] {
  const now = new Date();
  return allPostsMeta
    .filter(p => p.lang === lang && new Date(p.published_at) <= now)
    .sort((a, b) => new Date(b.published_at).getTime() - new Date(a.published_at).getTime());
}